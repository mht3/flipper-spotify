"""Export the stock u8g2 fonts from an Eddy firmware checkout for the LCD demo."""
import ast
import base64
import re
import sys
from pathlib import Path

FONTS = {
    "primary": "helvB08_tr",
    "secondary": "haxrcorp4089_tr",
    "keyboard": "profont11_mr",
    "big": "profont22_tn",
    "tiny": "5x7_tr",
}


def export(checkout):
    source = (checkout / "lib/u8g2/u8g2_fonts.c").read_text()
    lines = ["// Generated by tools/export_lcd_fonts.py from the firmware's stock fonts.",
             "export const fontData = {"]
    for name, symbol in FONTS.items():
        start = source.index("const uint8_t u8g2_font_" + symbol + "[")
        lines.append(source[source.rindex("/*", 0, start):start].strip())
        fragment = source[start:source.index('";', start) + 1]
        literals = re.findall(r'"(?:\\.|[^"\\])*"', fragment.partition("=")[2])
        payload = b"".join(ast.literal_eval("b" + literal) for literal in literals)
        lines.append(f"  {name}: '{base64.b64encode(payload).decode()}',")
    lines.append("};")
    dest = Path(__file__).resolve().parents[1] / "demo/lcd-fonts.js"
    dest.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    export(Path(sys.argv[1]))
