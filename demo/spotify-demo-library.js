export function drawIcon(ctx, name, x, y, scale=1) {
  const rows=icons[name] ?? icons.tracks;
  rows.forEach((bits,i)=>{
    for(let j=0;j<8;j++) if(bits & (128>>j)) ctx.fillRect(x+j*scale,y+i*scale,scale,scale);
  });
}
